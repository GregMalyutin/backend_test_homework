def format_workout(workout: dict) -> str:
    """Форматирует план тренировки в читаемый текст."""
    lines = [
        f"\n=== {workout['title']} ===",
        f"Цель: {workout['goal']}",
        f"Длительность: ~{workout['duration_min']} мин",
        "",
        "Упражнения:",
    ]
    for index, exercise in enumerate(workout["exercises"], start=1):
        lines.append(
            f"  {index}. {exercise['name']} — "
            f"{exercise['sets']} × {exercise['reps']}"
        )
        lines.append(f"     → {exercise['note']}")

    lines.append("")
    lines.append("Советы:")
    for tip in workout["tips"]:
        lines.append(f"  • {tip}")
    return "\n".join(lines)


def recommend(choice: str) -> str:
    """
    Возвращает план по выбору пользователя.

    choice:
      '1' или 'лестница' — кардио на лестничном тренажёре
      '2' или 'ноги'     — силовой день ног
    """
    normalized = choice.strip().lower()
    aliases = {
        "1": "1",
        "лестница": "1",
        "лестничный": "1",
        "stair": "1",
        "кардио": "1",
        "2": "2",
        "ноги": "2",
        "день ног": "2",
        "силовая": "2",
        "leg": "2",
        "legs": "2",
    }
    key = aliases.get(normalized)
    if key is None:
        return (
            "Неизвестный выбор. Введите:\n"
            "  1 / лестница — тренажёр-лестница\n"
            "  2 / ноги     — силовой день ног"
        )
    return format_workout(WORKOUTS[key])


def compare() -> str:
    """Краткое сравнение двух вариантов тренировки."""
    return (
        "\n=== Что выбрать? ===\n"
        "• Лестница — если нужно кардио, выносливость и сжечь калории "
        "без тяжёлой осевой нагрузки на позвоночник.\n"
        "• День ног — если цель сила, форма и рост мышц бёдер и ягодиц.\n"
        "• Оптимально чередовать: 1–2 силовых дня ног в неделю + "
        "1–2 сессии на лестнице в другие дни."
    )


def main() -> None:
    print("Фитнес-клуб: лестница или день ног?")
    print(compare())
    print("\nВыберите тренировку:")
    print("  1 — Тренажёр «лестница»")
    print("  2 — День ног (силовой)")
    print("  3 — Показать оба плана")
    choice = input("\nВаш выбор: ").strip().lower()

    if choice in {"3", "оба", "all"}:
        print(recommend("1"))
        print(recommend("2"))
    else:
        print(recommend(choice))


if __name__ == "__main__":
    main()
